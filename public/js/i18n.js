/** Translate a key. Falls back to English. {x} placeholders are replaced from vars. */
export function t(key, vars = {}) {
  const s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}

/** True if this key is shown in English because the current language lacks it. */
export const isFallback = (key) => current !== "en" && STRINGS[current][key] == null;
